const { chromium } = require('playwright');
const BASE = process.env.BREWHIVE_URL || 'http://localhost:4173';
const ok = (c, m) => { if (!c) throw new Error('FAILED: ' + m); console.log('ok  ' + m); };
(async () => {
  const b = await chromium.launch(); const p = await (await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })).newPage();
  const errors = []; p.on('pageerror', e => errors.push(e.message));
  await p.goto(BASE + '/'); await p.getByRole('button', { name: 'Load sample data' }).click(); await p.waitForSelector('.chips');
  const chip = (n) => p.getByRole('button', { name: new RegExp('^' + n) });
  ok(await chip('Archived').count() === 1, 'there is an Archived filter');
  await chip('Bottled').click();
  await p.getByRole('link', { name: /First Traditional/ }).first().click(); await p.waitForSelector('.hero');
  await p.getByRole('button', { name: 'Archive', exact: true }).click();
  await p.screenshot({ path: process.argv[2] + '/17-confirm.png' });
  await p.getByRole('dialog').getByRole('button', { name: 'Archive' }).click(); await p.waitForTimeout(300);
  ok(await p.locator('.archived-note').count() === 1 && await p.getByRole('group', { name: 'Status' }).count() === 0, 'archived batch shows the note instead of the status steps');
  ok(await p.locator('.hero .book, .hero svg').count() > 0, 'hero still has art');
  ok(await p.getByText('Archived', { exact: true }).count() > 0, 'labelled Archived');
  ok(await p.getByRole('button', { name: 'Archive', exact: true }).count() === 0, 'Archive button hidden once archived');
  ok(await p.getByText(/^Archived$/).first().isVisible(), 'timeline/hero mention Archived');
  await p.screenshot({ path: process.argv[2] + '/17-archived.png', fullPage: true });
  await p.goto(BASE + '/#/batches'); await p.waitForTimeout(200);
  await chip('Bottled').click();
  await p.waitForTimeout(300); await p.screenshot({ path: process.argv[2] + '/17-bottled.png' });
  ok(await p.getByRole('link', { name: /First Traditional/ }).count() === 0, 'gone from Bottled');
  ok(await p.getByText('No bottled batches.').count() === 1, 'empty Bottled filter says so instead of showing everything');
  await chip('Archived').click();
  ok(await p.getByRole('link', { name: /First Traditional/ }).count() === 1, 'listed under Archived');
  await p.screenshot({ path: process.argv[2] + '/17-shelf.png' });
  await p.getByRole('link', { name: /First Traditional/ }).click(); await p.waitForSelector('.hero');
  await p.getByRole('button', { name: 'Unarchive' }).click(); await p.waitForTimeout(300);
  ok(await p.getByRole('group', { name: 'Status' }).count() === 1 && (await p.locator('.hero-sub, .hero').first().textContent()).includes('Bottled'), 'unarchive returns it to Bottled');
  ok(await p.locator('.timeline-title', { hasText: /Archived|Unarchived/ }).count() === 0, 'archiving and unarchiving on the same day cancel out on the timeline');
  console.log(errors.length ? 'ERRORS ' + errors : 'no console errors'); await b.close();
})().catch(e => { console.error(e.message); process.exit(1); });
